/**
  * @brief  驱动层总初始化函数，依次初始化所有底层外设驱动
  * @param  无
  * @retval 无
  * @note   调用顺序：串口初始化 -> 定时器初始化 -> CAN滤波器初始化
  *         USART1: 通常用于调试串口或上位机通信
  *         USART3: 通常用于遥控器(DBUS)接收
  *         USART6: 通常用于裁判系统或其他串口设备通信
  *         TIM1:   用于PWM输出(如云台电机控制)
  *         TIM4:   用于蜂鸣器PWM输出或定时中断
  *         CAN:    初始化CAN1和CAN2的滤波器，用于电机通信
  */
void DRIVER_Init(void)
{
	USART1_Init();      /* 初始化串口1 */
	USART3_Init();      /* 初始化串口3 */
	USART6_Init();      /* 初始化串口6 */
	TIM1_Init();        /* 初始化定时器1 */
	TIM4_Init();        /* 初始化定时器4 */
	CAN_Filter_Init();  /* 初始化CAN总线滤波器 */
}
