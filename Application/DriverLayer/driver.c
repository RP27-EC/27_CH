/**
 * @brief  驱动层初始化函数
 * @param  无
 * @retval 无
 * @note   该函数在系统启动时调用，依次初始化所有串口和CAN总线
 *         初始化顺序：串口10 -> 串口5 -> 串口1 -> 串口7 -> 串口8 -> 串口9
 *         然后初始化三个CAN总线的滤波器：CAN1 -> CAN2 -> CAN3
 */
void DRIVER_Init(void)
{
	/* ---- 串口初始化部分 ---- */
	USART10_Init();    /* 初始化串口10（用于特定通信） */
	USART5_Init();     /* 初始化串口5（用于遥控器DBUS通信） */
	USART1_Init();     /* 初始化串口1（用于裁判系统等通信） */
	USART7_Init();     /* 初始化串口7（用于调试或扩展通信） */
	USART8_Init();     /* 初始化串口8（用于调试或扩展通信） */
	USART9_Init();     /* 初始化串口9（用于调试或扩展通信） */

	/* ---- CAN总线滤波器初始化部分 ---- */
	CAN1_Filter_Init(); /* 初始化CAN1滤波器，配置接收过滤规则 */
	CAN2_Filter_Init(); /* 初始化CAN2滤波器，配置接收过滤规则 */
	CAN3_Filter_Init(); /* 初始化CAN3滤波器，配置接收过滤规则 */
}
