/* 宏定义 ----------------------------------------------------------------------*/

/**
 * @brief 圆周率π的定义
 * @note  用于角度与弧度之间的转换计算
 */
#define VALUE_PI  3.145926f

/**
 * @brief 弧度转角度的转换系数
 * @note  角度 = 弧度 * RADIAN_CONVERSION_ANGLE
 */
#define RADIAN_CONVERSION_ANGLE (180/VALUE_PI)

/**
 * @brief 角度转弧度的转换系数
 * @note  弧度 = 角度 * ANGLE_CONVERSION_RADIAN
 */
#define ANGLE_CONVERSION_RADIAN (VALUE_PI/180)
